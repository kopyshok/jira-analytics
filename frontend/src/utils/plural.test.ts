import { describe, expect, it } from 'vitest';
import { plural } from './plural';

const tasks = (n: number) => `${n} ${plural(n, 'задача', 'задачи', 'задач')}`;

describe('склонение после числа', () => {
  it.each([
    [0, '0 задач'], [1, '1 задача'], [2, '2 задачи'], [4, '4 задачи'], [5, '5 задач'],
    [11, '11 задач'], [12, '12 задач'], [14, '14 задач'], [21, '21 задача'],
    [22, '22 задачи'], [25, '25 задач'], [76, '76 задач'], [101, '101 задача'],
    [111, '111 задач'], [112, '112 задач'], [1001, '1001 задача'],
  ])('%i → %s', (n, expected) => {
    expect(tasks(n)).toBe(expected);
  });

  it('отрицательные числа склоняются по модулю', () => {
    expect(plural(-1, 'день', 'дня', 'дней')).toBe('день');
    expect(plural(-3, 'день', 'дня', 'дней')).toBe('дня');
    expect(plural(-11, 'день', 'дня', 'дней')).toBe('дней');
  });

  it('дробное число — родительный единственного: «1,5 дня»', () => {
    expect(plural(1.5, 'день', 'дня', 'дней')).toBe('дня');
    expect(plural(0.5, 'день', 'дня', 'дней')).toBe('дня');
  });
});
